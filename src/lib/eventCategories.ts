export const eventCategorySlugs = new Set(eventCategories.map((category) => category.slug));

export function getAssignedTagSlugs() {
	const slugs = new Set<string>();
	for (const category of eventCategories) {
		if (category.slug === OTHERS_CATEGORY_SLUG) continue;
		for (const tag of category.tags) slugs.add(tag.slug);
	}
	return slugs;
}

export function eventMatchesOthersCategory(tags?: string[] | null) {
	if (!tags?.length) return true;
	const assigned = getAssignedTagSlugs();
	return tags.some((slug) => !assigned.has(slug));
}

export function resolveTagIdsForCategories(args: {
	categorySlugs: string[];
	tags: { id: number; slug: string }[];
}) {
	if (!args.categorySlugs?.length) return [];

	const includeOthers = args.categorySlugs.includes(OTHERS_CATEGORY_SLUG);
	const assigned = includeOthers ? getAssignedTagSlugs() : null;
	const mappedSlugs = new Set<string>();
	for (const categorySlug of args.categorySlugs) {
		if (categorySlug === OTHERS_CATEGORY_SLUG) continue;
		const category = eventCategories.find((item) => item.slug === categorySlug);
		if (!category?.tags?.length) continue;
		for (const tag of category.tags) mappedSlugs.add(tag.slug);
	}

	const ids: number[] = [];
	for (const tag of args.tags) {
		if (mappedSlugs.has(tag.slug)) {
			ids.push(tag.id);
			continue;
		}
		if (includeOthers && assigned && !assigned.has(tag.slug)) ids.push(tag.id);
	}
	return ids;
}

type EventTag = {
	slug: string;
	get label(): string;
};

type EventCategory = {
	slug: string;
	label: string;
	tags: EventTag[];
};

export const allTags = new Set(uniqueTagsBySlug(eventCategories.flatMap((category) => category.tags)));

function uniqueTagsBySlug(tags: EventTag[]) {
	const bySlug = new Map<string, EventTag>();
	for (const tag of tags) {
		if (bySlug.has(tag.slug)) continue;
		bySlug.set(tag.slug, tag);
	}
	return [...bySlug.values()];
}